def render_candidates(data: dict[str, Any], lang: str) -> str:
    lines = banner(data, lang, choose(lang, "Candidates and unresolved transfers", "候補と未導出の項目"))
    lines += [f"[{choose(lang, 'Catalog', '一覧')}]({filename('CATALOG', lang)})", "",
              choose(lang,
                     "These entries are not established consequences in this catalog. Failure of a particular kernel/encoding route is not an impossibility result, a lower bound, or a statement about the best known algorithm.",
                     "以下は本カタログで導出済みの帰結ではありません。特定のカーネル・符号化による導出が得られないことは、不可能性・下界・最良既知アルゴリズムについての主張ではありません。"), ""]
    if not data["candidates"]:
        lines += [choose(lang, "No candidates are recorded.", "候補は記録されていません。"), ""]
    for candidate in data["candidates"]:
        local = candidate[lang]
        candidate_track = candidate.get("track")
        measure_label = (choose(lang, "**Size measure.** ", "**サイズ尺度。** ") if candidate_track == "exact"
                         else choose(lang, "**Parameter.** ", "**パラメータ。** ") if candidate_track == "fpt"
                         else choose(lang, "**Parameter or size measure.** ", "**パラメータまたはサイズ尺度。** "))
        lines += [f"## {local['name']}", "", f"ID: `{candidate['id']}`", "",
                  choose(lang, "Track: ", "区分：") + (f"`{candidate_track}`" if candidate_track else choose(lang, "Unassigned", "未指定")), "",
                  choose(lang, "Claim status: ", "主張の状態：") + f"`{candidate['claim_status']}`; "
                  + choose(lang, "review: ", "確認：") + f"`{candidate['review_status']}`", "",
                  measure_label + local["parameter"], "",
                  choose(lang, "**Obstacle for this route.** ", "**この方法での障害。** ") + local["obstacle"], "",
                  choose(lang, "**Next step.** ", "**次に確認すること。** ") + local["next_step"], "",
                  choose(lang, "**Sources.**", "**出典。**"), ""]
        lines += source_lines(candidate["source_refs"], data["sources"], lang, candidate=True)
        if candidate.get("review_history"):
            for record in candidate["review_history"]:
                lines += [f"- {record['date']} — {record['reviewer']} (`{record['reviewer_type']}`): {record['scope']}"]
            lines += [""]
    return finish(lines)


def render_assumptions(data: dict[str, Any], lang: str) -> str:
    lines = banner(data, lang, choose(lang, "Assumptions and source versions", "仮定と出典の版"))
    lines += [f"[{choose(lang, 'Catalog', '一覧')}]({filename('CATALOG', lang)})", "",
              choose(lang,
                     "The assumptions are separate inputs to the derivations. In particular, a stronger paper bound must not be silently attributed to a separately reported formalization with a weaker bound. Source versions and locators below record provenance, not an independent correctness audit.",
                     "各仮定は導出に用いる別個の前提です。特に、原稿の強い上界を、より弱い上界が報告されている形式化にそのまま帰属させてはいけません。以下の版・参照箇所は出典の記録であり、独立の正確性監査ではありません。"), ""]
    for assumption in data["assumptions"]:
        lines += [f"## {assumption['id']}", "", assumption["description"][lang], "",
                  choose(lang, "**Assumed time bound**", "**仮定する時間上界**"), "",
                  "$$", assumption["time_tex"], "$$", "",
                  choose(lang, "**Assumed space bound**", "**仮定する領域上界**"), "",
                  "$$", assumption["space_tex"], "$$", ""]
        lines += source_lines([{"source_id": assumption["source_id"], "locator": assumption["locator"]}], data["sources"], lang)
    lines += [choose(lang, "# Source register", "# 出典一覧"), ""]
    for source_id in sorted(data["sources"]):
        source = data["sources"][source_id]
        lines += [f"## {source_id}", "", f"[{source['title']}]({source['url']})", "",
                  choose(lang, "- Version: ", "- 版：") + source["version"],
                  choose(lang, "- Locator: ", "- 参照箇所：") + source["locator"]]
        if "sha256" in source:
            lines += [f"- SHA-256: `{source['sha256']}`"]
        lines += [""]
    return finish(lines)


def finish(lines: list[str]) -> str:
    return "\n".join(lines).rstrip() + "\n"


def rendered_files(data: dict[str, Any]) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for lang in LANGUAGES:
        outputs[Path(filename("CATALOG", lang))] = render_index(data, lang)
        outputs[Path(filename("FPT", lang))] = render_index(data, lang, "fpt")
        outputs[Path(filename("EXACT", lang))] = render_index(data, lang, "exact")
        outputs[Path(filename("CANDIDATES", lang))] = render_candidates(data, lang)
        outputs[Path(filename("ASSUMPTIONS", lang))] = render_assumptions(data, lang)
        for entry in data["entries"]:
            outputs[Path("docs") / lang / f"{entry['id']}.md"] = render_entry(data, entry, lang)
    return outputs


def reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValidationError(f"JSON contains duplicate object key {key!r}")
        result[key] = value
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate and detect missing/stale generated files without writing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="catalog root directory (default: parent of tools/)")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        source = root / "data" / "catalog.json"
        data = validate(json.loads(source.read_text(encoding="utf-8"), object_pairs_hook=reject_duplicate_keys))
        outputs = rendered_files(data)
        problems = []
        for relative, contents in outputs.items():
            destination = root / relative
            expected = contents.encode("utf-8")
            if args.check:
                if not destination.is_file():
                    problems.append(f"missing: {relative.as_posix()}")
                elif destination.read_bytes() != expected:
                    problems.append(f"stale: {relative.as_posix()}")
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                if not destination.exists() or destination.read_bytes() != expected:
                    destination.write_bytes(expected)
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            print("Run python3 tools/render_catalog.py to regenerate. Mechanical checks do not verify proofs.", file=sys.stderr)
            return 1
        verb = "Checked" if args.check else "Rendered"
        print(f"{verb} {len(outputs)} files from {len(data['entries'])} entries and {len(data['candidates'])} candidates.")
        print("Schema/render checks only; no mathematical proof or novelty verification.")
        return 0
    except (ValidationError, json.JSONDecodeError, UnicodeError, OSError) as error:
        print(f"catalog error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
